#!/usr/bin/env node
// Builds the shipment map from Natural Earth data (world-atlas, public domain) with d3-geo.
// Output is static SVG path data plus projected pins and route, so the client ships no geo code.
// Run: node scripts/build-map.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { geoNaturalEarth1, geoPath, geoGraticule10, geoInterpolate, geoDistance } from "d3-geo";
import { feature, mesh } from "topojson-client";
import { presimplify, simplify, sphericalTriangleArea } from "topojson-simplify";

const W = 720, H = 300;
// Keep only detail that survives at panel size: drop vertices whose triangle area is under ~0.6 sq px.
const world = simplify(presimplify(JSON.parse(readFileSync("node_modules/world-atlas/countries-50m.json", "utf8")), sphericalTriangleArea), 5e-6);
const land = feature(world, world.objects.land);
const borders = mesh(world, world.objects.countries, (a, b) => a !== b);

// [lon, lat]
const PLACES = {
  Stuttgart: [9.18, 48.78], Osaka: [135.5, 34.69], Shenzhen: [114.27, 22.57], Dongguan: [113.75, 23.02],
  "Long Beach": [-118.19, 33.77], Chicago: [-87.63, 41.88],
};

// Pacific in the middle; frame Europe to the US Midwest.
const frame = { type: "MultiPoint", coordinates: [[0, 62], [0, 8], [140, 66], [140, 4], [-75, 56], [-75, 18], [70, 2], [-150, 64]] };
const projection = geoNaturalEarth1().rotate([-150, 0]).fitExtent([[12, 10], [W - 12, H - 10]], frame);
projection.clipExtent([[0, 0], [W, H]]);
const path = geoPath(projection).digits(0);

// Route: sea leg on the great circle Shenzhen to Long Beach, then rail to Chicago.
function sample(a, b, n) {
  const f = geoInterpolate(a, b);
  return Array.from({ length: n + 1 }, (_, i) => f(i / n));
}
const sea = sample(PLACES.Shenzhen, PLACES["Long Beach"], 80);
const rail = sample(PLACES["Long Beach"], PLACES.Chicago, 16).slice(1);
const legKm = (pts) => pts.slice(1).reduce((s, p, i) => s + geoDistance(pts[i], p) * 6371, 0);
const route = [...sea, ...rail].map((p) => projection(p).map((v) => Math.round(v * 10) / 10));
const seaShare = legKm(sea) / (legKm(sea) + legKm([PLACES["Long Beach"], ...rail]));

const pins = Object.fromEntries(Object.entries(PLACES).map(([k, v]) => [k, projection(v).map((n) => Math.round(n * 10) / 10)]));
const out = {
  width: W, height: H,
  land: path(land),
  borders: path(borders),
  graticule: path(geoGraticule10()),
  pins,
  route,
  seaPoints: sea.length,
  seaShare: Math.round(seaShare * 1000) / 1000,
  seaKm: Math.round(legKm(sea)),
  railKm: Math.round(legKm([PLACES["Long Beach"], ...rail])),
};
const ts = `// Generated by scripts/build-map.mjs from Natural Earth 1:50m (world-atlas, public domain). Do not edit.
export const MAP = ${JSON.stringify(out)} as const;
`;
writeFileSync("components/workspace/map/generated.ts", ts);
console.log(`wrote map: ${(ts.length / 1024).toFixed(0)} KB, land ${(out.land.length / 1024).toFixed(0)} KB, sea ${out.seaKm} km, rail ${out.railKm} km`);
console.log(JSON.stringify(pins));
