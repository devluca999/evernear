#!/usr/bin/env node
// Builds the shipment map from Natural Earth data (world-atlas, public domain) with d3-geo.
// Output is static SVG path data plus projected pins and route, so the client ships no geo code.
// Run: node scripts/build-map.mjs
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { geoNaturalEarth1, geoPath, geoGraticule10, geoInterpolate, geoDistance } from "d3-geo";
import { feature, mesh } from "topojson-client";
import { presimplify, simplify, sphericalTriangleArea } from "topojson-simplify";

const W = 720, H = 300;
// Keep only detail that survives at panel size: drop vertices whose triangle area is under ~0.6 sq px.
const world = simplify(presimplify(JSON.parse(readFileSync("node_modules/world-atlas/countries-50m.json", "utf8")), sphericalTriangleArea), 5e-6);
const land = feature(world, world.objects.land);
const borders = mesh(world, world.objects.countries, (a, b) => a !== b);

// [lon, lat]
const PLACES = {
  Stuttgart: [9.18, 48.78], Osaka: [135.5, 34.69], Shenzhen: [114.27, 22.57], Dongguan: [113.75, 23.02], Chicago: [-87.63, 41.88],
  Rockford: [-89.09, 42.27],
};
// Each supplier's headquarters. The lane to Chicago is a great circle (air), or a road for Ultra Motion.
const SUPPLIER_PLACE = { ultra: "Rockford", haoyun: "Shenzhen", kansai: "Osaka", rheinwerk: "Stuttgart", huaxin: "Dongguan" };
// Air freight: Haoyun's dock to Shenzhen Bao'an (SZX) by truck, SZX to O'Hare (ORD) by air, ORD to Astro's dock by truck.
const SZX = [113.81, 22.64], ORD = [-87.9, 41.98];

function sample(a, b, n) {
  const f = geoInterpolate(a, b);
  return Array.from({ length: n + 1 }, (_, i) => f(i / n));
}
const truckOut = sample(PLACES.Shenzhen, SZX, 3);
const flight = sample(SZX, ORD, 120).slice(1);
const truckIn = sample(ORD, PLACES.Chicago, 3).slice(1);
const km = (pts) => pts.slice(1).reduce((s, p, i) => s + geoDistance(pts[i], p) * 6371, 0);

// Pacific in the middle; frame Europe, the whole flight arc and the US Midwest.
const frame = { type: "MultiPoint", coordinates: [[0, 58], [0, 8], [-70, 20], [100, 4], ...flight, ...Object.values(PLACES)] };
const projection = geoNaturalEarth1().rotate([-150, 0]).fitExtent([[14, 14], [W - 14, H - 12]], frame);
projection.clipExtent([[0, 0], [W, H]]);
const path = geoPath(projection).digits(0);

const geo = [...truckOut, ...flight, ...truckIn];
const route = geo.map((p) => projection(p).map((v) => Math.round(v * 10) / 10));
const pins = Object.fromEntries(Object.entries(PLACES).map(([k, v]) => [k, projection(v).map((n) => Math.round(n * 10) / 10)]));
/** A lane as projected segments, split where it crosses the map's edge. */
function lane(a, b, n) {
  const segs = [[]];
  let prev = null;
  for (const p of sample(a, b, n).map((q) => projection(q).map((v) => Math.round(v * 10) / 10))) {
    if (prev && Math.abs(p[0] - prev[0]) > W / 2) segs.push([]);
    segs.at(-1).push(p);
    prev = p;
  }
  return segs.filter((x) => x.length > 1);
}
const lanes = Object.fromEntries(Object.entries(SUPPLIER_PLACE).map(([id, place]) => [id, {
  place, segments: lane(PLACES[place], PLACES.Chicago, 80), km: Math.round(km(sample(PLACES[place], PLACES.Chicago, 80))),
}]));
const out = {
  width: W, height: H,
  land: path(land),
  borders: path(borders),
  graticule: path(geoGraticule10()),
  pins,
  route,
  /** Each supplier's lane to Chicago: projected segments and great-circle km. */
  lanes,
  /** Route indices of each stop: Haoyun dock, SZX, ORD, Astro dock. */
  stops: { origin: 0, szx: truckOut.length - 1, ord: truckOut.length - 1 + flight.length, dock: route.length - 1 },
  airKm: Math.round(km([SZX, ...flight])),
  roadKm: Math.round(km(truckOut) + km([ORD, ...truckIn])),
};
const ts = `// Generated by scripts/build-map.mjs from Natural Earth 1:50m (world-atlas, public domain). Do not edit.
export const MAP = ${JSON.stringify(out)} as const;
`;
writeFileSync("components/workspace/map/generated.ts", ts);
// The detailed map: finer coastlines and borders (Natural Earth 1:50m, light simplification, 0.1 px
// precision), in the same projection. Loaded by the page after first paint, so zooming in stays crisp.
const fine = simplify(presimplify(JSON.parse(readFileSync("node_modules/world-atlas/countries-50m.json", "utf8")), sphericalTriangleArea), 1e-7);
const finePath = geoPath(projection).digits(1);
mkdirSync("public/map", { recursive: true });
const detail = JSON.stringify({ land: finePath(feature(fine, fine.objects.land)), borders: finePath(mesh(fine, fine.objects.countries, (a, b) => a !== b)) });
writeFileSync("public/map/world-detail.json", detail);
console.log(`wrote detail map: ${(detail.length / 1024).toFixed(0)} KB`);
console.log(`wrote map: ${(ts.length / 1024).toFixed(0)} KB, air ${out.airKm} km, road ${out.roadKm} km, max lat ${Math.max(...flight.map((p) => p[1])).toFixed(1)}`);
console.log(JSON.stringify(pins));
